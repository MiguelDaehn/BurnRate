# In reporting.py

def create_pdf_report(motor: MotorConfig, t, Pc_MPa, F, It, filename="report.pdf"):
    set_plot_style()
    pdf = DashboardPDF()
    pdf.add_page()

    # 1. TITLE
    pdf.ln(2)
    pdf.set_font('Helvetica', '', 11)
    pdf.set_text_color(*COLOR_TEXT)
    pdf.cell(0, 8, f"Performance Analysis for Configuration: {motor.name}", 0, 1, 'L')

    # 2. KPI DASHBOARD
    peak_p = np.max(Pc_MPa)
    max_f = np.max(F)
    cls = get_impulse_class(It)

    start_y = pdf.get_y() + 2
    pdf.draw_kpi_card(15, start_y, "Total Impulse", f"{It:.1f}", f"Ns (Class {cls})", is_primary=True)
    pdf.draw_kpi_card(62, start_y, "Peak Pressure", f"{peak_p:.2f}", "MPa")
    pdf.draw_kpi_card(109, start_y, "Peak Thrust", f"{max_f:.0f}", "Newtons")
    pdf.draw_kpi_card(156, start_y, "Burn Time", f"{t[-1]:.2f}", "Seconds")

    pdf.set_y(start_y + 32)

    # 3. CONFIGURATION TABLE
    pdf.draw_section_title("Technical Specifications")
    config_headers = ["Parameter", "Value", "Unit"]
    config_data = get_config_table_data(motor)
    pdf.draw_clean_table(config_headers, config_data, [80, 50, 30], start_x=25)
    pdf.ln(8)

    # 4. PLOTS
    pdf.draw_section_title("Thrust & Pressure Telemetry")
    temp_img = "temp_dashboard_plot.png"

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(8, 6), height_ratios=[1, 0.8])

    # Thrust (Teal)
    ax1.plot(t, F, color='#00a0aa', linewidth=2, label='Thrust')
    ax1.fill_between(t, F, alpha=0.1, color='#00a0aa')
    ax1.set_ylabel('Thrust (N)')
    ax1.legend(loc='upper right', frameon=False)

    # Pressure (Dark Blue)
    ax2.plot(t, Pc_MPa, color='#121e32', linewidth=2, label='Pressure')
    ax2.fill_between(t, Pc_MPa, alpha=0.05, color='#121e32')
    ax2.set_xlabel('Time (s)')
    ax2.set_ylabel('Pressure (MPa)')
    ax2.legend(loc='upper right', frameon=False)

    plt.tight_layout()
    plt.savefig(temp_img, dpi=300)
    plt.close(fig)

    pdf.image(temp_img, x=15, w=180)
    if os.path.exists(temp_img): os.remove(temp_img)

    # 5. FOOTER SUMMARY
    pdf.ln(5)
    pdf.set_font('Helvetica', 'I', 9)
    pdf.set_text_color(*COLOR_TEXT)
    pdf.cell(0, 5, f"Summary: Class {cls} motor delivering {It:.0f} Ns with a peak thrust of {max_f:.0f} N.", 0, 1, 'C')

    # --- FIX: Trust the provided filename path ---
    # Ensure directory exists
    output_dir = os.path.dirname(filename)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir)

    pdf.output(filename)
    print(f"✅ Design Report generated: {filename}")

