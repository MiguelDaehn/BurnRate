# REPORT 2: SENSITIVITY (Blue/Teal)
# ==========================================
def create_sensitivity_report(base_motor, param_name, values_to_test, filename="sensitivity.pdf"):
    set_plot_style()
    pdf = DashboardPDF()
    pdf.add_page()

    # 1. TITLE
    pdf.ln(2)
    pdf.set_font('Helvetica', 'B', 14)
    pdf.set_text_color(*COLOR_PRIMARY)
    pdf.cell(0, 10, f"Sensitivity Analysis: Varying '{param_name}'", 0, 1, 'L')

    # 2. CONFIGURATION TABLE (SINGLE SET OF COLUMNS)
    pdf.draw_section_title("Base Configuration")
    config_headers = ["Parameter", "Value", "Unit"]
    config_data = get_config_table_data(base_motor)
    pdf.draw_clean_table(config_headers, config_data, [80, 50, 30], start_x=25)
    pdf.ln(5)

    # 3. RUN SIMS
    from thrust import calculate_thrust
    results_data = []

    # Plot setup
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))

    # Colormap: Blend form Dark Blue (#121e32) to Teal (#00a0aa)
    import matplotlib.colors as mcolors
    cmap = mcolors.LinearSegmentedColormap.from_list("BlueTeal", ["#121e32", "#00a0aa"])
    colors = [cmap(i) for i in np.linspace(0, 1, len(values_to_test))]

    for i, val in enumerate(values_to_test):
        sim_motor = copy.deepcopy(base_motor)
        if hasattr(sim_motor, param_name):
            setattr(sim_motor, param_name, val)

        F, Pc, t, Cf, It = calculate_thrust(10000, sim_motor, 0.95, 6.278)

        peak_p = np.max(Pc)
        max_f = np.max(F)
        cls = get_impulse_class(It)

        val_str = f"{val:.3f}" if isinstance(val, (float, np.floating)) else str(val)
        results_data.append([val_str, f"{peak_p:.3f}", f"{max_f:.1f}", f"{It:.1f}", cls])

        ax1.plot(t, Pc, label=val_str, color=colors[i], linewidth=1.5, alpha=0.8)
        ax2.plot(t, F, color=colors[i], linewidth=1.5, alpha=0.8)

    # Style Plots
    for ax in [ax1, ax2]:
        ax.grid(True, color='#00a0aa', alpha=0.1)

    ax1.set_title("Chamber Pressure (MPa)", color='#121e32', fontweight='bold')
    ax1.set_xlabel("Time (s)")
    ax1.legend(title=param_name, fontsize=7, frameon=False)

    ax2.set_title("Thrust (N)", color='#00a0aa', fontweight='bold')
    ax2.set_xlabel("Time (s)")

    plt.tight_layout()
    temp_img = "temp_sens_plot.png"
    plt.savefig(temp_img, dpi=300)
    plt.close(fig)

    # 4. PLOTS
    pdf.draw_section_title("Visual Comparison")
    pdf.image(temp_img, x=15, w=180)
    if os.path.exists(temp_img): os.remove(temp_img)

    # 5. DATA TABLE
    pdf.ln(5)
    pdf.draw_section_title("Comparative Data")
    headers = [param_name, "Peak P (MPa)", "Max F (N)", "Impulse (Ns)", "Class"]
    pdf.draw_clean_table(headers, results_data, [35, 35, 35, 35, 30], start_x=20)

    output_dir = os.path.dirname(filename)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir, exist_ok=True)
    print(f"✅ Sensitivity Report generated: {filename}")