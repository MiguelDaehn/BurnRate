# --- THEME PALETTE (Dark Blue, White, Teal) ---
COLOR_PRIMARY = (18, 30, 50)  # Deep Midnight Blue
COLOR_WHITE = (255, 255, 255)  # Crisp White
COLOR_TEAL = (0, 160, 170)  # Electric Teal
COLOR_NEUTRAL = (240, 245, 248)  # Light Blue-Grey
COLOR_TEXT = (50, 60, 70)  # Dark Slate

LOGO_FILENAME = 'tau_logo.png'


class DashboardPDF(FPDF):
    def header(self):
        # --- 0. BACKGROUND WATERMARK ---
        # Draw this first so it sits behind everything else
        if os.path.exists(LOGO_FILENAME):
            # Save current position
            original_y = self.get_y()

            # Calculate centered position for watermark (approx 140mm wide)
            wm_width = 140
            wm_x = (210 - wm_width) / 2
            wm_y = (297 - wm_width) / 2  # Center vertically roughly

            # Draw faded/large image
            # Note: Standard FPDF doesn't support alpha transparency easily without extensions.
            # We assume the png has transparency or is light enough.
            self.image(LOGO_FILENAME, x=wm_x, y=wm_y, w=wm_width)

            # Reset position for normal content
            self.set_y(original_y)

        # --- 1. DARK BLUE HEADER BAR ---
        self.set_fill_color(*COLOR_PRIMARY)
        self.rect(0, 0, 210, 22, 'F')

        # --- 2. LOGO / BRAND TEXT ---
        self.set_font('Helvetica', 'B', 12)
        self.set_text_color(*COLOR_TEAL)
        self.set_xy(10, 6)
        self.cell(0, 5, 'TAU ROCKET TEAM', 0, 0, 'L')

        # --- 3. MAIN TITLE ---
        self.set_font('Helvetica', 'B', 20)
        self.set_text_color(*COLOR_WHITE)
        self.set_xy(10, 11)
        self.cell(0, 8, 'SRM SIMULATION REPORT', 0, 0, 'L')

        # --- 4. TOP RIGHT LOGO ---
        if os.path.exists(LOGO_FILENAME):
            # Position: Top right, inside the blue bar
            # x=185 (210 - 25 margin), y=2, w=20
            self.image(LOGO_FILENAME, x=185, y=2, w=18)

        # --- 5. ACCENT STRIP ---
        self.set_fill_color(*COLOR_TEAL)
        self.rect(0, 22, 210, 1.5, 'F')

        self.ln(25)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', '', 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by SRM Simulator', 0, 0, 'R')

    def draw_section_title(self, title):
        """Clean header with Teal underline"""
        self.ln(5)
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(*COLOR_PRIMARY)
        self.cell(0, 8, title.upper(), 0, 1, 'L')

        # Teal Underline
        self.set_fill_color(*COLOR_TEAL)
        self.rect(self.get_x(), self.get_y(), 30, 1, 'F')
        self.ln(6)

    def draw_kpi_card(self, x, y, label, value, unit, is_primary=False):
        """Modern 'Card' style for stats"""
        width, height = 42, 26

        # Card Background
        self.set_fill_color(255, 255, 255)
        self.set_draw_color(220, 220, 220)
        self.set_line_width(0.2)
        self.rounded_rect(x, y, width, height, 2, 'FD')

        # Left Accent Bar
        bar_color = COLOR_TEAL if is_primary else COLOR_PRIMARY
        self.set_fill_color(*bar_color)
        self.rounded_rect(x, y, 3, height, 2, 'F')
        self.rect(x + 1.5, y, 1.5, height, 'F')

        # Content
        off_x = x + 5
        self.set_xy(off_x, y + 4)
        self.set_font('Helvetica', 'B', 7)
        self.set_text_color(120, 130, 140)
        self.cell(width - 5, 4, label.upper(), 0, 0, 'L')

        self.set_xy(off_x, y + 10)
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(*COLOR_PRIMARY)
        self.cell(width - 5, 7, value, 0, 0, 'L')

        self.set_xy(off_x, y + 17)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(*COLOR_TEAL)
        self.cell(width - 5, 5, unit, 0, 0, 'L')

    def rounded_rect(self, x, y, w, h, r, style=''):
        """Helper to draw rounded rectangles"""
        k = 0.5522847498
        op = style.upper()
        if op == 'F':
            op_str = 'f'
        elif op == 'FD' or op == 'DF':
            op_str = 'B'
        else:
            op_str = 'S'

        self._out(f'{x + r:.2f} {y:.2f} m')
        self._out(f'{x + w - r:.2f} {y:.2f} l')
        self._out(f'{x + w - r + r * k:.2f} {y:.2f} {x + w:.2f} {y + r - r * k:.2f} {x + w:.2f} {y + r:.2f} c')
        self._out(f'{x + w:.2f} {y + h - r:.2f} l')
        self._out(
            f'{x + w:.2f} {y + h - r + r * k:.2f} {x + w - r + r * k:.2f} {y + h:.2f} {x + w - r:.2f} {y + h:.2f} c')
        self._out(f'{x + r:.2f} {y + h:.2f} l')
        self._out(f'{x + r - r * k:.2f} {y + h:.2f} {x:.2f} {y + h - r + r * k:.2f} {x:.2f} {y + h - r:.2f} c')
        self._out(f'{x:.2f} {y + r:.2f} l')
        self._out(f'{x:.2f} {y + r - r * k:.2f} {x + r - r * k:.2f} {y:.2f} {x + r:.2f} {y:.2f} c')
        self._out(op_str)

    def draw_clean_table(self, headers, data, col_widths, start_x=15):
        """Minimalist Table"""
        self.set_x(start_x)

        # Header
        self.set_font('Helvetica', 'B', 9)
        self.set_text_color(*COLOR_WHITE)
        self.set_fill_color(*COLOR_PRIMARY)
        self.set_draw_color(*COLOR_PRIMARY)

        for i, h in enumerate(headers):
            self.cell(col_widths[i], 8, h, 0, 0, 'C', fill=True)
        self.ln()

        # Data
        self.set_font('Helvetica', '', 9)
        self.set_text_color(*COLOR_TEXT)
        self.set_draw_color(230, 230, 230)

        for idx, row in enumerate(data):
            self.set_x(start_x)
            # Zebra Striping
            if idx % 2 == 0:
                self.set_fill_color(255, 255, 255)
            else:
                self.set_fill_color(*COLOR_NEUTRAL)

            for i, d in enumerate(row):
                if i == 0:
                    self.set_font('Helvetica', 'B', 9)
                    self.set_text_color(*COLOR_PRIMARY)
                else:
                    self.set_font('Helvetica', '', 9)
                    self.set_text_color(*COLOR_TEXT)
                self.cell(col_widths[i], 7, str(d), 'B', 0, 'C', fill=True)
            self.ln()


# --- HELPER: Class Calculator ---
def get_impulse_class(It):
    limits = [
        (2.5, 'A'), (5, 'B'), (10, 'C'), (20, 'D'), (40, 'E'), (80, 'F'),
        (160, 'G'), (320, 'H'), (640, 'I'), (1280, 'J'), (2560, 'K'),
        (5120, 'L'), (10240, 'M'), (20480, 'N'), (40960, 'O')
    ]
    return next((char for limit, char in limits if It <= limit), "P+")


# --- PLOTTING STYLE ---
def set_plot_style():
    plt.style.use('default')
    rcParams.update({
        'font.family': 'sans-serif',
        'font.sans-serif': ['Arial', 'Helvetica', 'DejaVu Sans'],
        'font.size': 9,
        'axes.facecolor': 'white',
        'axes.edgecolor': '#E0E0E0',
        'axes.linewidth': 0.8,
        'axes.grid': True,
        'grid.color': '#00a0aa',
        'grid.alpha': 0.1,
        'grid.linestyle': '-',
        'xtick.color': '#555555',
        'ytick.color': '#555555',
        'text.color': '#333333',
        'axes.labelcolor': '#121e32',
        'figure.facecolor': 'white',
        'savefig.dpi': 300,
        'savefig.bbox': 'tight'
    })


# --- HELPER: CONFIG TABLE DATA (SINGLE COLUMN FORMAT) ---
def get_config_table_data(motor):
    # Flattened format: Parameter | Value | Unit
    return [
        ["Motor ID", motor.name, "-"],
        ["Propellant", motor.prop, "-"],
        ["Grain Length", f"{motor.L:.1f}", "mm"],
        ["Grain OD", f"{motor.De:.1f}", "mm"],
        ["Grain ID", f"{motor.Di:.1f}", "mm"],
        ["No. of Grains", str(motor.Ng), "-"],
        ["Throat Dia", f"{motor.Dt:.2f}", "mm"],
        ["Target Pressure", f"{motor.P_target:.1f}", "MPa"],
    ]


